@njit(cache=True)
def dist_point_to_line_segment(p, a, b):
    ap = p - a
    ab = b - a
    dot_ab = np.dot(ab, ab)
    t = np.dot(ap, ab) / (dot_ab + 1e-9)
    t = max(0.0, min(1.0, t))
    closest = a + t * ab
    return np.linalg.norm(p - closest)

